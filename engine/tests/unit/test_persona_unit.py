"""HAC-38 P6.1 (AM-2 D2, addendum G32): the seeded persona.

One prepared, clearly fictional member with 28 days of saved check-ins, generated by the committed
``tools/make_persona.py`` and replayed through the real check-in service (create, then review), so
the member app opens populated and every value went through the same pipeline a person's would.
A fresh, empty journal stays available.
"""

from __future__ import annotations

import datetime as dt
import importlib.util
import json
from pathlib import Path

import pytest

fastapi = pytest.importorskip("fastapi")
from fastapi.testclient import TestClient  # noqa: E402

from daypart.checkin.journal import DEFAULT_TODAY  # noqa: E402
from daypart.demo import persona  # noqa: E402
from daypart.demo.app import create_app  # noqa: E402

ENGINE = Path(__file__).resolve().parents[2]


@pytest.fixture()
def client():
    with pytest.MonkeyPatch.context() as mp:
        mp.delenv("DAYPART_REAL_INPUT", raising=False)
        with TestClient(create_app(cohort_seed=0)) as c:
            yield c


def _seeded(client):
    r = client.post("/api/journals", json={"persona": persona.PERSONA_ID})
    assert r.status_code == 201, r.text
    return r.json()


def test_persona_file_is_fictional_and_covers_28_days():
    p = persona.load_persona()
    assert p.persona_id == persona.PERSONA_ID and p.fictional is True
    assert p.member_id.startswith("syn-")
    days = [c.day for c in p.checkins]
    assert days == sorted(days) and len(set(days)) == 28
    assert days[-1] == DEFAULT_TODAY and days[0] == DEFAULT_TODAY - dt.timedelta(days=27)
    assert "fictional" in p.note.lower()


def test_persona_file_equals_the_generator_output():
    spec = importlib.util.spec_from_file_location("make_persona", ENGINE / "tools/make_persona.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    committed = json.loads((ENGINE / "daypart/demo/persona_v1.json").read_text())
    assert mod.build() == committed


def test_personas_route_lists_the_persona(client):
    r = client.get("/api/personas")
    assert r.status_code == 200
    p = persona.load_persona()
    assert r.json() == [{"persona_id": p.persona_id, "display_name": p.display_name}]


def test_seeded_journal_has_every_checkin_saved_through_review(client):
    body = _seeded(client)
    p = persona.load_persona()
    assert body["member_id"] == p.member_id and body["display_name"] == p.display_name
    assert body["persona_id"] == p.persona_id and body["today"] == DEFAULT_TODAY.isoformat()
    j = client.app.state.journals.get(body["journal_id"])
    assert len(j.saved_order) == 28 and all(c.status == "saved" for c in j.checkins.values())
    assert len(j.events) == j.event_count > 28
    # every record is a confirmed save on its own day, through the text extractor
    days = {c.day for c in p.checkins}
    for rec in j.provenance.values():
        assert rec.quality == "confirmed" and rec.status == "mapped"
        assert rec.provenance.source_kind == "text"
        assert rec.observed_at.date() in days


def test_seeded_journal_opens_populated(client):
    jid = _seeded(client)["journal_id"]
    pp = client.get(f"/api/journals/{jid}/passport").json()
    observed = [c for c in pp["cards"] if c["kind"] == "observation" and c["origin"] == "observed" and c["status"] == "ready"]
    assert len(observed) >= 5
    step = client.get(f"/api/journals/{jid}/next-step")
    assert step.status_code == 200 and step.json()["intent"] != "clinician_handoff"
    tl = client.get(f"/api/journals/{jid}/timeline").json()["entries"]
    assert len(tl) == 28 and all(e["appends"] for e in tl)
    assert any(c["change"] == "value_changed" for e in tl for c in e["passport_changes"])


def test_seeded_checkins_are_reviewable_links(client):
    jid = _seeded(client)["journal_id"]
    j = client.app.state.journals.get(jid)
    for cid in j.saved_order:
        assert client.app.state.journals.checkin_owner(cid) == jid


def test_each_seed_is_its_own_journal(client):
    a, b = _seeded(client)["journal_id"], _seeded(client)["journal_id"]
    assert a != b
    ja, jb = client.app.state.journals.get(a), client.app.state.journals.get(b)
    assert ja.events is not jb.events and len(ja.events) == len(jb.events)


def test_a_fresh_journal_stays_available_and_empty(client):
    r = client.post("/api/journals", json={"member_id": "syn-001"})
    assert r.status_code == 201
    body = r.json()
    assert "display_name" not in body and "persona_id" not in body
    assert client.get(f"/api/journals/{body['journal_id']}/next-step").status_code == 409


@pytest.mark.parametrize(
    "payload, status, error",
    [
        ({"persona": "persona-nope"}, 404, "unknown_persona"),
        ({"persona": 7}, 404, "unknown_persona"),
        ({"persona": persona.PERSONA_ID, "member_id": "syn-001"}, 422, "invalid_request"),
    ],
)
def test_bad_persona_requests(client, payload, status, error):
    r = client.post("/api/journals", json=payload)
    assert r.status_code == status and r.json() == {"error": error}


def test_a_persona_text_that_does_not_replay_cleanly_fails_loudly(monkeypatch):
    p = persona.load_persona()
    bad = p.model_copy(update={"checkins": (p.checkins[0].model_copy(update={"text": "slept 7"}),)})
    monkeypatch.setattr(persona, "load_persona", lambda: bad)
    with TestClient(create_app(cohort_seed=0), raise_server_exceptions=False) as c:
        r = c.post("/api/journals", json={"persona": persona.PERSONA_ID})
    assert r.status_code == 500 and r.json() == {"error": "persona_seed_failed"}
    assert len(c.app.state.journals) == 0  # the half-seeded journal is dropped


def test_k2_seed_response_names_the_saved_checkins(client):
    """QG P6.1 C1: the member app needs the persona's saved check-in ids, so its #review/<id> evidence
    links say "Already saved" instead of "not available here"."""
    body = _seeded(client)
    j = client.app.state.journals.get(body["journal_id"])
    assert body["saved_checkins"] == j.saved_order and len(body["saved_checkins"]) == 28

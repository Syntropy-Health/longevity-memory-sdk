"""Render ``docs/daypart/submission/outcomes.md`` from ``lab_rows()`` (A&D §4.11, T11.2).

The outcomes table is generated, never hand-typed: every number in it comes from ``lab_rows()``
over the committed ``docs/daypart/results/`` (A&D §4.8). A field ``lab_rows()`` could not read is
"not recorded"; a provenance-mismatch row and the proposed GRPO row carry no number.

Run from ``engine/``::

    uv run python tools/render_outcomes.py           # rewrite outcomes.md
    uv run python tools/render_outcomes.py --check   # exit 1 if outcomes.md is stale

The output is deterministic (no timestamps), so a unit test can compare it byte for byte.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from daypart.demo.lab import NOT_RECORDED, PROPOSED, PROVENANCE_MISMATCH, LabRow, LabTable, lab_rows

REPO = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = REPO / "docs" / "daypart" / "submission" / "outcomes.md"
NA = "n/a"
SHA_CHARS = 12


def _cell(v: Any) -> str:
    """One table cell: never empty, no raw pipe or newline (they would break the table)."""
    s = NOT_RECORDED if v is None or v == "" else str(v)
    return s.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def _num(v: float | int | None) -> str:
    return NOT_RECORDED if v is None else repr(v)


def _metrics(m: Mapping[str, float | None]) -> str:
    if not m:
        return NOT_RECORDED
    return "; ".join(f"{k} {_num(v)}" for k, v in sorted(m.items()))


def _seed(v: int | list[int] | None) -> str:
    if v is None:
        return NOT_RECORDED
    return ", ".join(str(s) for s in v) if isinstance(v, list) else str(v)


def _sha(v: str | None) -> str:
    return NOT_RECORDED if not v else v[:SHA_CHARS]


def _gate(g: Mapping[str, Any] | None, row: str) -> str:
    if row == "base":
        return NA
    if not isinstance(g, Mapping) or not isinstance(g.get("passed"), bool):
        return NOT_RECORDED
    return "passed" if g["passed"] else "failed"


def _row(cells: Sequence[Any]) -> str:
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def _model_line(r: LabRow) -> str:
    sp = r.split
    prompt_set = sp.prompt_set_version if sp else None
    if r.status == PROVENANCE_MISMATCH:
        # G25: a mismatch row keeps only the run id, prompt set and data sha; no number at all.
        data = _sha(sp.data_sha256 if sp else None)
        withheld = PROVENANCE_MISMATCH
        return _row([r.row, r.status, r.run_id, f"{_cell(prompt_set)}; data sha256 {data}",
                     withheld, withheld, withheld, withheld, withheld])
    split = f"{_cell(prompt_set)}; n {_num(sp.n if sp else None)}"
    if r.row == "base":
        split += f"; file sha256 {_sha(r.file_digest)}"
    else:
        split += (f"; training rows {_num(sp.training_rows if sp else None)}"
                  f"; data sha256 {_sha(sp.data_sha256 if sp else None)}")
    return _row([r.row, r.status, r.run_id, split, _seed(r.seed), _num(r.failures),
                 _num(r.degenerate), _metrics(r.metrics), _gate(r.gate, r.row)])


def _env_line(r: LabRow) -> str:
    sp = r.split
    split = (f"{_num(sp.n_scenarios if sp else None)} scenarios; {_num(sp.n if sp else None)} episodes; "
             f"horizon {_num(sp.horizon if sp else None)}")
    return _row([r.row, r.status, r.run_id, split, _seed(r.seed), _num(r.failures), _metrics(r.metrics)])


def render(table: LabTable) -> str:
    models = [r for r in table.rows if r.kind == "model"]
    envs = [r for r in table.rows if r.kind == "env_baseline"]
    proposed = [r for r in table.rows if r.kind == "proposed"]
    i1 = NOT_RECORDED if table.i1_passed is None else ("passed" if table.i1_passed else "failed")
    out = [
        "<!-- Generated by engine/tools/render_outcomes.py from lab_rows(). Do not edit by hand. -->",
        "# Outcomes: the learning lab",
        "",
        "This table is generated from the committed results in [`docs/daypart/results/`](../results/)",
        "by `engine/tools/render_outcomes.py`, through the same `lab_rows()` the hosted learning lab",
        "uses (A&D §4.8). It is never typed by hand: a unit test (T11.2) fails if it differs from a fresh",
        "render. A field that no committed artefact records reads \"not recorded\".",
        "",
        "Regenerate it from `engine/` with `uv run python tools/render_outcomes.py`.",
        "",
        "## Model arms: boundary evaluation on the held-out prompt set",
        "",
        "Source: `docs/daypart/results/boundary_eval.json`, with `training.json` for the sft and dpo",
        "adapters and `pipeline.json` for the run id. `failures` counts prompts that failed the",
        "boundary check; `degenerate` counts empty or collapsed outputs, shown separately.",
        "",
        "| row | status | run id | split | seed | failures | degenerate | metrics | gate |",
        "|---|---|---|---|---|---|---|---|---|",
        *(_model_line(r) for r in models),
        "",
        "## Scripted SimMember baselines",
        "",
        "Source: `docs/daypart/results/metrics.json`. Each arm runs every scenario under each seed, so",
        "episodes = scenarios × seeds. These are scripted policies in a synthetic simulator.",
        "",
        "| row | status | run id | split | seeds | failures | metrics |",
        "|---|---|---|---|---|---|---|",
        *(_env_line(r) for r in envs),
        "",
        "## Proposed, not built",
        "",
        "| row | status | reason |",
        "|---|---|---|",
        *(_row([r.row, PROPOSED, r.reason]) for r in proposed),
        "",
        "## Checks",
        "",
        f"- I1 builder check: {i1} (the curated-25 held-out profiles appear in no training or eval"
        " builder's output; `metrics.json`, arm `i1_gate`).",
        f"- Synthetic members whose narrative generation failed: {_num(table.member_failure_count)}"
        " (`pipeline.json`, `member_failure_count`).",
        "",
        f"> {table.footer}",
        "",
    ]
    return "\n".join(out)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    ap.add_argument("--results", type=Path, default=None, help="results dir (default: committed)")
    ap.add_argument("--check", action="store_true", help="exit 1 if --output differs from a render")
    args = ap.parse_args(argv)
    text = render(lab_rows(args.results))
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else None
        if current != text:
            print(f"{args.output} is stale; run tools/render_outcomes.py", file=sys.stderr)
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
